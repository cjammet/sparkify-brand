"""Build tokens/tokens.css from design-system/tokens.json.

Usage (from the repo root):  python scripts/build_tokens.py

tokens.json is the source of truth. tokens.css is generated for the website and
anything else that wants CSS custom properties. Light is the default theme;
dark applies under [data-theme="dark"] and prefers-color-scheme: dark.
"""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "design-system" / "tokens.json"
OUT = ROOT / "tokens" / "tokens.css"


def theme_value(value, theme, first):
    if isinstance(value, str):
        return value
    return value.get(theme, value.get(first))


def main():
    t = json.loads(SRC.read_text(encoding="utf-8"))
    themes = [th["id"] for th in t["color"]["themes"]]
    first = themes[0]
    themed = t["color"]["tokens"] + t.get("shadow", {}).get("tokens", [])

    def block(theme):
        return [f"  --{tok['name']}: {theme_value(tok['value'], theme, first)};" for tok in themed]

    lines = ["/* Generated by scripts/build_tokens.py from design-system/tokens.json. Do not edit by hand. */", ""]
    lines += [":root, [data-theme=\"%s\"] {" % first] + block(first) + ["}", ""]
    for theme in themes[1:]:
        lines += [f"[data-theme=\"{theme}\"] {{"] + block(theme) + ["}", ""]
        lines += ["@media (prefers-color-scheme: dark) {", "  :root:not([data-theme=\"%s\"]) {" % first]
        lines += ["  " + l for l in block(theme)] + ["  }", "}", ""]
    lines.append(":root {")
    for fam in ("spacing", "radius"):
        for tok in t.get(fam, {}).get("tokens", []):
            lines.append(f"  --{tok['name']}: {tok['value']};")
    for key, stack in t["type"]["families"].items():
        lines.append(f"  --font-{key}: {stack};")
    lines += ["}", ""]
    for group in t["type"]["groups"]:
        for st in group["styles"]:
            fam = st.get("family", group["family"])
            props = [f"font-family: var(--font-{fam})", f"font-size: {st['fontSize']}", f"line-height: {st['lineHeight']}", f"font-weight: {st['fontWeight']}"]
            if "letterSpacing" in st:
                props.append(f"letter-spacing: {st['letterSpacing']}")
            if st.get("textTransform"):
                props.append(f"text-transform: {st['textTransform']}")
            lines.append(f".{st['name']} {{ " + "; ".join(props) + "; }")
    OUT.parent.mkdir(exist_ok=True)
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"Wrote {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
